#!/usr/bin/env python3
"""Write the OpenClaw bridge's wallet fixture from every shield's packs and browser roots.

Usage::

    uv run python scripts/gen_openclaw_wallets.py

The bridge (``integrations/openclaw``) has no wallet detector yet; the day it grows
one, it reads ``integrations/openclaw/src/generated/wallets.json`` instead of keeping
its own list. Every registered shield (``shields.all_shields()``) contributes its
loaded packs - every kind's own block as the manifest states it (Chromium and Firefox
ids under ``stores``, app ``places``, the cli-key-file ``pointer``) - and its
``browsers.json`` roots, so the fixture never drifts from what the Python guard uses.

The output is deterministic (sorted keys, packs in display order, roots in file
order, one trailing newline): re-running it on unchanged data changes nothing.
tests/plugins/test_blackbox_openclaw_wallets_fixture.py regenerates it in memory and
fails when the committed file differs, so a pack or root change ships with its
regenerated fixture.

Fails closed: a pack that loads ``unavailable`` or a browser root that is dropped
stops the run with the loader's reasons, so a broken pack never silently vanishes
from the fixture.
"""

from __future__ import annotations

import importlib
import importlib.util
import json
import sys
import types
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]
PLUGIN_DIR = REPO_ROOT / "plugins" / "blackbox"
FIXTURE = REPO_ROOT / "integrations" / "openclaw" / "src" / "generated" / "wallets.json"

#: The package name the plugin loader (and tests/plugins/_blackbox_loader.py) mounts the plugin under.
PLUGIN_PACKAGE = "hermes_plugins.blackbox"
GENERATED_NOTE = ("GENERATED by scripts/gen_openclaw_wallets.py from every shield's packs and browsers.json"
                  " - DO NOT EDIT. Regenerate: uv run python scripts/gen_openclaw_wallets.py")
#: Pack fields the bridge needs besides the kind's own block (folder, logo and provenance stay behind).
PACK_FIELDS = ("id", "name", "kind", "status", "order")


class FixtureError(RuntimeError):
    """A shield's packs or roots did not load cleanly; the message lists the loader's reasons."""


def _plugin_module(name: str) -> types.ModuleType:
    """``hermes_plugins.blackbox.<name>``, mounting the plugin first unless it already is."""
    if PLUGIN_PACKAGE not in sys.modules:
        root = sys.modules.setdefault("hermes_plugins", types.ModuleType("hermes_plugins"))
        if not hasattr(root, "__path__"):
            root.__path__ = []
        spec = importlib.util.spec_from_file_location(
            PLUGIN_PACKAGE, PLUGIN_DIR / "__init__.py", submodule_search_locations=[str(PLUGIN_DIR)]
        )
        if spec is None or spec.loader is None:
            raise FixtureError(f"{PLUGIN_DIR} is not a Python package")
        package = importlib.util.module_from_spec(spec)
        sys.modules[PLUGIN_PACKAGE] = package
        spec.loader.exec_module(package)
    return importlib.import_module(f"{PLUGIN_PACKAGE}.{name}")


def _pack_json(pack: Any) -> dict[str, Any]:
    """One pack as its manifest states it, minus the folder, logo and provenance."""
    return {**{field: getattr(pack, field) for field in PACK_FIELDS}, **pack.data}


def build_fixture() -> dict[str, Any]:
    """``{"shields": {id: {"packs": [...], "browser_roots": [...]}}}`` for every registered shield."""
    shields = _plugin_module("shields")
    loader = _plugin_module("shields.packs")
    by_shield: dict[str, Any] = {}
    for shield in shields.all_shields():
        data = loader.load_shield_data(shield)
        problems = [f"{pack.id}: {pack.reason}" for pack in data.packs if pack.status == "unavailable"]
        problems += list(data.health)
        if problems:
            raise FixtureError(f"shield {shield.id} did not load cleanly: " + "; ".join(problems))
        by_shield[shield.id] = {
            "packs": [_pack_json(pack) for pack in data.packs],
            "browser_roots": [root.as_json() for root in data.roots],
        }
    return {"_generated": GENERATED_NOTE, "shields": by_shield}


def render() -> str:
    """The fixture file's exact text."""
    return json.dumps(build_fixture(), indent=2, sort_keys=True, ensure_ascii=True) + "\n"


def main() -> int:
    try:
        text = render()
    except FixtureError as exc:
        print(f"gen_openclaw_wallets: {exc}", file=sys.stderr)
        return 1
    FIXTURE.parent.mkdir(parents=True, exist_ok=True)
    FIXTURE.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {FIXTURE.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
